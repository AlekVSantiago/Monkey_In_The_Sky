function handleJump () {
    if (controller.A.isPressed()) {
        if (isGrounded) {
            Shakespeare.vy = -90
            jumpTimer = 0
        } else if (jumpTimer < jumpEndTimer) {
            Shakespeare.vy = -90
            // Shakespeare.vy = -100
            jumpTimer += changeNumber
        }
    } else if (!(controller.A.isPressed())) {
        jumpTimer = jumpEndTimer
    }
}
